import { SHOW_PRICES } from "@/lib/settings";
import Link from "next/link";
import { db } from "@/lib/db";
import { requireUser } from "@/lib/auth";
import { fmtDate, money, prettyReg, normReg } from "@/lib/format";

export const dynamic = "force-dynamic";

export default async function BillsPage({ searchParams }) {
  const user = await requireUser("/bills");
  const sp = await searchParams;
  const q = String(sp.q || "").trim();
  const reg = normReg(q);

  // STRICT ACCESS: Only show bills belonging to the logged-in user
  const where = {
    userId: user.id,
    ...(q
      ? {
          OR: [
            { number: { contains: q } },
            { vehicle: { regNo: { contains: reg || q } } },
            { vehicle: { make: { contains: q } } },
            { vehicle: { model: { contains: q } } },
          ],
        }
      : {}),
  };

  const bills = await db.bill.findMany({
    where,
    orderBy: { createdAt: "desc" },
    include: { vehicle: true },
  });
  const due = bills.filter((b) => !b.paid).reduce((a, b) => a + b.total, 0);

  return (
    <div className="container page">
      <div className="page-head">
        <div>
          <span className="eyebrow">Billing</span>
          <h1>My bills &amp; Invoices</h1>
          <div className="muted small">
            All invoices with unique serial numbers issued to your account.
          </div>
        </div>
        {SHOW_PRICES.customerBills && due > 0 && (
          <div className="badge unpaid" style={{ fontSize: "0.9rem", padding: "8px 14px" }}>
            Outstanding: {money(due)}
          </div>
        )}
      </div>

      {/* Customer search by serial number / vehicle */}
      <form className="searchbar" method="get">
        <input
          name="q"
          defaultValue={q}
          placeholder="Search your bills by Serial Number (e.g. INV-0001) or Vehicle…"
        />
        <button className="btn btn-dark">Search</button>
        {q && <Link href="/bills" className="btn btn-ghost">Clear</Link>}
      </form>

      <div className="table-wrap">
        <table className="tbl">
          <thead>
            <tr>
              <th>Serial No</th>
              <th>Date</th>
              <th>Vehicle</th>
              {SHOW_PRICES.customerBills && <th className="num">Amount</th>}
              <th>Status</th>
              <th />
            </tr>
          </thead>
          <tbody>
            {bills.map((b) => (
              <tr key={b.id}>
                <td>
                  <b className="mono" style={{ color: "var(--ink)", letterSpacing: "0.02em" }}>
                    {b.number}
                  </b>
                </td>
                <td>{fmtDate(b.createdAt)}</td>
                <td>
                  {b.vehicle.make} {b.vehicle.model}{" "}
                  <span className="reg">{prettyReg(b.vehicle.regNo)}</span>
                </td>
                {SHOW_PRICES.customerBills && (
                  <td className="num mono">
                    <b>{money(b.total)}</b>
                  </td>
                )}
                <td>
                  <span className={`badge ${b.paid ? "paid" : "unpaid"}`}>
                    {b.paid ? "Paid" : "Due"}
                  </span>
                </td>
                <td className="right">
                  <Link href={`/bills/${b.id}`} className="btn btn-ghost btn-sm">
                    Open Invoice
                  </Link>
                </td>
              </tr>
            ))}
            {bills.length === 0 && (
              <tr>
                <td colSpan={SHOW_PRICES.customerBills ? 6 : 5}>
                  <div className="empty">
                    {q
                      ? `No bills found matching “${q}”.`
                      : "No bills yet. Invoices generated by the garage for your vehicles will appear here."}
                  </div>
                </td>
              </tr>
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
}
